"""Write the `oan-partner-gateway` Helm chart (APISIX Ingress Controller resources)
from the ADC files of the partner APIs.

The routes are built by ../apisix-gateway/build_apisix_config.py (`./build.sh deploy`:
PARTNER_AUTH=oauth, every upstream host a placeholder), the same config the sandbox is
tested against locally. ADC must not be run against a gateway that the APISIX Ingress
Controller manages (each overwrites the other), so on Kubernetes the same routes are
installed as ApisixRoute / ApisixUpstream / ApisixPluginConfig resources:

    python deploy/apisix-partner-gateway/generate_k8s_chart.py \\
        ../apisix-gateway/generated/deploy/partner-apis.adc.yaml

Only what partners call: `./build.sh deploy` leaves out the routes staff use (staff have
their own portals).

Each ADC service becomes one API of the chart, switched on by its own value (`API`):

    ApisixUpstream       the upstream host
    ApisixPluginConfig   the service's plugins, the same on every route of the API (the app
                         token check, the call log). Routes point at it
                         (`plugin_config_name`); with `inlineSharedPlugins: true` they
                         carry a copy instead.
    ApisixRoute          one rule per operation, with only its own plugins (the rate limit)

ADC placeholders become chart values (`PLACEHOLDERS`). `request-id` is left out: the
gateway has it as a global rule. The ADC file's `global_rules` and `plugin_metadata` are
not written here either: they are gateway-wide and belong to the oan-apisix-gateway chart
(`gatewayProxy.plugins`, `gatewayProxy.pluginMetadata`).
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml

CHART = Path(__file__).resolve().parent / "k8s"
HEADER = (
    "# OAN partner APIs (sandbox apps, GATEWAY_PARTNER_AUTH=oauth): APISIX Ingress Controller resources.\n"
    "# Generated by deploy/apisix-partner-gateway/generate_k8s_chart.py from {source} -- do not hand-edit;\n"
    "# change build_apisix_config.py and re-run.\n"
)
#: ADC service -> the value that switches its API on.
API = {
    "consent-manager-staff-api": "consentManager.portalApi.enabled",
    "consent-manager-partner-api": "consentManager.partnerApi.enabled",
    "partner-management-keys-api": "partnerManagement.keysApi.enabled",
    "aggregation-layer-api": "aggregationLayer.enabled",
}
#: Resource names that differ from the ADC service's: of the console host's service only
#: the partner portal routes are in the chart.
NAMES = {"consent-manager-staff-api": "consent-manager-partner-portal-api"}


def _required(path: str) -> str:
    return '{{ required "%s is required" .Values.%s }}' % (path, path)


PLACEHOLDERS = {
    "${PARTNER_KEYCLOAK_ISSUER}": '{{ include "partnerGateway.issuer" . }}',
    "${PARTNER_KEYCLOAK_DISCOVERY}": '{{ include "partnerGateway.discovery" . }}',
    "${PARTNER_ENVIRONMENT_ROLE}": _required("environmentRole"),
    "${CONSENT_MANAGER_STAFF_HOST}": _required("consentManager.portalApi.host"),
    "${CONSENT_MANAGER_PARTNER_HOST}": _required("consentManager.partnerApi.host"),
    # A path the upstream serves the API under; empty = at the root.
    "${CONSENT_MANAGER_PARTNER_BASE_PATH}": '{{ .Values.consentManager.partnerApi.basePath | trimSuffix "/" }}',
    "${PARTNER_MANAGEMENT_KEYS_HOST}": _required("partnerManagement.keysApi.host"),
    "${AGGREGATION_LAYER_HOST}": _required("aggregationLayer.host"),
    "${SANDBOX_LOG_INGEST_URL}": _required("callLog.url"),
}
# Apps share a gateway and pick routes by host: hosts is required (checked in apisix-tls.yaml).
HOSTS = (
    "      hosts:\n"
    "{{- range .Values.hosts }}\n"
    "      - {{ . | quote }}\n"
    "{{- end }}\n"
)
# limit-count counters shared by every APISIX pod when redis.host is set.
def _redis(indent: int) -> str:
    pad = " " * indent
    return (
        "{{- if .Values.redis.host }}\n"
        + f"{pad}policy: redis\n"
        + pad + "redis_host: {{ .Values.redis.host | quote }}\n"
        + pad + "redis_port: {{ .Values.redis.port }}\n"
        + "{{- end }}\n"
    )


class _Literal(str):
    pass


def _literal(dumper: yaml.Dumper, value: _Literal) -> yaml.ScalarNode:
    return dumper.represent_scalar("tag:yaml.org,2002:str", value, style="|")


yaml.add_representer(_Literal, _literal)


def _blocks(value):
    """Multi-line strings (the serverless Lua) as literal blocks."""
    if isinstance(value, dict):
        return {k: _blocks(v) for k, v in value.items()}
    if isinstance(value, list):
        return [_blocks(v) for v in value]
    if isinstance(value, str) and "\n" in value:
        return _Literal(value)
    return value


def _dump(value, indent: int) -> str:
    text = yaml.dump(_blocks(value), sort_keys=False, default_flow_style=False, width=4096, allow_unicode=True)
    if "{{" in text or "}}" in text:
        raise ValueError("a plugin config holds '{{' or '}}', which Helm would read as a template")
    pad = " " * indent
    return "".join(pad + line if line.strip() else line for line in text.splitlines(True))


def _k8s_name(name: str) -> str:
    return re.sub(r"[^a-z0-9-]", "-", NAMES.get(name, name).lower()).strip("-")


def _duration(seconds) -> str:
    return f"{seconds}s"


def _enabled(service: dict) -> str:
    return "{{- if .Values.%s }}\n" % API[service["name"]]


def _shared(service: dict) -> dict:
    """The service's plugins: the ones every route of the API shares."""
    return {k: v for k, v in (service.get("plugins") or {}).items() if k != "request-id"}


def _template(service: dict) -> str:
    return f"partnerGateway.plugins.{_k8s_name(service['name'])}"


def _plugin(name: str, config: dict, indent: int) -> str:
    pad = " " * indent
    body = _dump(config, indent + 4)
    if name == "limit-count":
        body += _redis(indent + 4)
    item = f"{pad}- name: {name}\n{pad}  enable: true\n{pad}  config:\n{body}"
    if name == "http-logger":
        # The call log is optional: the sandbox stores the records only when its
        # GATEWAY_LOG_INGEST_ENABLED is on.
        item = "{{- if .Values.callLog.enabled }}\n" + item + "{{- end }}\n"
    return item


def shared_plugins(service: dict) -> str:
    """A named template with the API's shared plugins, used by its ApisixPluginConfig and,
    with inlineSharedPlugins, by every route."""
    items = "".join(_plugin(name, config, 0) for name, config in _shared(service).items())
    return '{{- define "%s" -}}\n%s{{- end }}\n' % (_template(service), items)


def upstream(service: dict) -> str:
    up = service["upstream"]
    node = up["nodes"][0]
    timeout = up.get("timeout") or {}
    if not str(node["host"]).startswith("${"):
        raise ValueError(
            f"{service['name']}: the upstream host {node['host']!r} is fixed (built with a local"
            " *_UPSTREAM_URL); build with `./build.sh deploy` first"
        )
    spec = {
        "externalNodes": [{"type": "Domain", "name": node["host"], "port": node["port"]}],
        "scheme": up.get("scheme", "http"),
        "passHost": up.get("pass_host", "pass"),
        "retries": up.get("retries", 1),
        "timeout": {k: _duration(v) for k, v in timeout.items()},
    }
    return (
        _enabled(service)
        + "apiVersion: apisix.apache.org/v2\n"
        "kind: ApisixUpstream\n"
        "metadata:\n"
        f"  name: {_k8s_name(service['name'])}\n"
        "  labels:\n"
        "    app: oan-partner-gateway\n"
        "spec:\n"
        "  ingressClassName: {{ .Values.ingressClassName | quote }}\n"
        + _dump(spec, 2)
        + "{{- end }}\n"
    )


def plugin_config(service: dict) -> str:
    return (
        "{{- if and .Values.%s (not .Values.inlineSharedPlugins) }}\n" % API[service["name"]]
        + "apiVersion: apisix.apache.org/v2\n"
        "kind: ApisixPluginConfig\n"
        "metadata:\n"
        f"  name: {_k8s_name(service['name'])}\n"
        "  labels:\n"
        "    app: oan-partner-gateway\n"
        "spec:\n"
        "  ingressClassName: {{ .Values.ingressClassName | quote }}\n"
        "  plugins:\n"
        '{{ include "%s" . | indent 2 }}\n' % _template(service)
        + "{{- end }}\n"
    )


def route(service: dict) -> str:
    name = _k8s_name(service["name"])
    out = [
        _enabled(service),
        "apiVersion: apisix.apache.org/v2\n",
        "kind: ApisixRoute\n",
        "metadata:\n",
        f"  name: {name}\n",
        "  labels:\n",
        "    app: oan-partner-gateway\n",
        "spec:\n",
        "  ingressClassName: {{ .Values.ingressClassName | quote }}\n",
        "  http:\n",
    ]
    for r in service["routes"]:
        out.append(f"  - name: {r['name']}\n")
        if r.get("priority"):
            out.append(f"    priority: {r['priority']}\n")
        out.append("    match:\n")
        out.append(HOSTS)
        out.append("      paths:\n")
        out.extend(f"      - {uri}\n" for uri in r["uris"])
        out.append("      methods:\n")
        out.extend(f"      - {m}\n" for m in r["methods"])
        out.append("    upstreams:\n")
        out.append(f"    - name: {name}\n")
        out.append("{{- if not .Values.inlineSharedPlugins }}\n")
        out.append(f"    plugin_config_name: {name}\n")
        out.append("{{- end }}\n")
        own = r.get("plugins") or {}
        if own:
            out.append("    plugins:\n")
            out.append("{{- if .Values.inlineSharedPlugins }}\n")
            out.append('{{ include "%s" $ | indent 4 }}\n' % _template(service))
            out.append("{{- end }}\n")
            for plugin_name, config in own.items():
                out.append(_plugin(plugin_name, config, 4))
        else:
            # Nothing of its own: the shared plugins are all it has.
            out.append("{{- if .Values.inlineSharedPlugins }}\n")
            out.append("    plugins:\n")
            out.append('{{ include "%s" $ | indent 4 }}\n' % _template(service))
            out.append("{{- end }}\n")
    out.append("{{- end }}\n")
    return "".join(out)


def main(sources: list[str]) -> int:
    services = []
    for source in sources:
        adc = yaml.safe_load(Path(source).read_text(encoding="utf-8"))
        found = adc.get("services") or []
        if not found:
            print(f"{source}: no services", file=sys.stderr)
            return 1
        services.extend(found)
    unknown = [s["name"] for s in services if s["name"] not in API]
    if unknown:
        print(
            f"services that are not partner APIs of the chart (API): {unknown}."
            " Build with `./build.sh deploy`, which leaves staff routes out.",
            file=sys.stderr,
        )
        return 1
    header = HEADER.format(source=", ".join(Path(source).name for source in sources))
    files = {
        "apisix-upstream.yaml": header + "---\n".join(upstream(s) for s in services),
        "apisix-pluginconfig.yaml": header + "---\n".join(plugin_config(s) for s in services),
        "apisix-route.yaml": header + "---\n".join(route(s) for s in services),
        "_shared-plugins.tpl": "{{/*\n" + header + "*/}}\n" + "".join(shared_plugins(s) for s in services),
    }
    for name, text in files.items():
        for placeholder, expression in PLACEHOLDERS.items():
            text = text.replace(placeholder, expression)
        files[name] = text
    left = set(re.findall(r"\$\{[A-Z_]+\}", "".join(files.values())))
    if left:
        print(f"unmapped ADC placeholders: {sorted(left)}", file=sys.stderr)
        return 1
    (CHART / "templates").mkdir(parents=True, exist_ok=True)
    for name, text in files.items():
        (CHART / "templates" / name).write_text(text, encoding="utf-8", newline="\n")
    count = sum(len(s["routes"]) for s in services)
    print(f"{len(services)} APIs (upstream + plugin config), {count} routes -> {CHART / 'templates'}")
    return 0


if __name__ == "__main__":
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(2)
    sys.exit(main(sys.argv[1:]))
