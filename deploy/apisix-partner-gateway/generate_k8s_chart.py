"""Write the `oan-partner-gateway` Helm chart (APISIX Ingress Controller resources)
from an ADC file of the partner APIs.

The routes are built by ../apisix-gateway/build_apisix_config.py (PARTNER_AUTH=oauth),
the same config the sandbox is tested against locally. ADC must not be run against a
gateway that the APISIX Ingress Controller manages (each overwrites the other), so on
Kubernetes the same routes are installed as ApisixRoute / ApisixUpstream resources:

    python deploy/apisix-partner-gateway/generate_k8s_chart.py \\
        ../apisix-gateway/generated/farmer-registry.adc.yaml

ADC placeholders become chart values:

    ${PARTNER_KEYCLOAK_ISSUER}       keycloak.issuer
    ${PARTNER_KEYCLOAK_DISCOVERY}    keycloak.discovery (empty = <issuer>/.well-known/openid-configuration)
    ${PARTNER_ENVIRONMENT_ROLE}      environmentRole
    ${FARMER_REGISTRY_UPSTREAM_HOST} farmerRegistry.upstreamHost
    ${FARMER_REGISTRY_KEYCLOAK_HOST} farmerRegistry.keycloakHost
    ${FARMER_REGISTRY_KEYCLOAK_REALM} farmerRegistry.keycloakRealm

Service-level plugins move onto every route of the service (an ApisixRoute has no
service); `request-id` is left out because the gateway has it as a global rule.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml

CHART = Path(__file__).resolve().parent / "k8s"
HEADER = (
    "# OAN partner APIs (sandbox apps, GATEWAY_PARTNER_AUTH=oauth): APISIX Ingress Controller resources.\n"
    "# Generated by deploy/apisix-partner-gateway/generate_k8s_chart.py from {source} -- do not hand-edit;\n"
    "# change build_apisix_config.py and re-run.\n"
)
PLACEHOLDERS = {
    "${PARTNER_KEYCLOAK_ISSUER}": '{{ include "partnerGateway.issuer" . }}',
    "${PARTNER_KEYCLOAK_DISCOVERY}": '{{ include "partnerGateway.discovery" . }}',
    "${PARTNER_ENVIRONMENT_ROLE}": '{{ required "environmentRole is required" .Values.environmentRole }}',
    "${FARMER_REGISTRY_UPSTREAM_HOST}": '{{ required "farmerRegistry.upstreamHost is required" .Values.farmerRegistry.upstreamHost }}',
    "${FARMER_REGISTRY_KEYCLOAK_HOST}": '{{ required "farmerRegistry.keycloakHost is required" .Values.farmerRegistry.keycloakHost }}',
    "${FARMER_REGISTRY_KEYCLOAK_REALM}": '{{ required "farmerRegistry.keycloakRealm is required" .Values.farmerRegistry.keycloakRealm }}',
}
# Apps share a gateway and pick routes by host: hosts is required (checked in apisix-tls.yaml).
HOSTS = (
    "      hosts:\n"
    "{{- range .Values.hosts }}\n"
    "      - {{ . | quote }}\n"
    "{{- end }}\n"
)
# limit-count counters shared by every APISIX pod when redis.host is set.
REDIS = (
    "{{- if .Values.redis.host }}\n"
    "        policy: redis\n"
    "        redis_host: {{ .Values.redis.host | quote }}\n"
    "        redis_port: {{ .Values.redis.port }}\n"
    "{{- end }}\n"
)


class _Literal(str):
    pass


def _literal(dumper: yaml.Dumper, value: _Literal) -> yaml.ScalarNode:
    return dumper.represent_scalar("tag:yaml.org,2002:str", value, style="|")


yaml.add_representer(_Literal, _literal)


def _blocks(value):
    """Multi-line strings (the serverless Lua) as literal blocks."""
    if isinstance(value, dict):
        return {k: _blocks(v) for k, v in value.items()}
    if isinstance(value, list):
        return [_blocks(v) for v in value]
    if isinstance(value, str) and "\n" in value:
        return _Literal(value)
    return value


def _dump(value, indent: int) -> str:
    text = yaml.dump(_blocks(value), sort_keys=False, default_flow_style=False, width=4096, allow_unicode=True)
    pad = " " * indent
    return "".join(pad + line if line.strip() else line for line in text.splitlines(True))


def _k8s_name(name: str) -> str:
    return re.sub(r"[^a-z0-9-]", "-", name.lower()).strip("-")


def _duration(seconds) -> str:
    return f"{seconds}s"


def upstream(service: dict) -> str:
    up = service["upstream"]
    node = up["nodes"][0]
    timeout = up.get("timeout") or {}
    spec = {
        "externalNodes": [{"type": "Domain", "name": node["host"], "port": node["port"]}],
        "scheme": up.get("scheme", "http"),
        "passHost": up.get("pass_host", "pass"),
        "retries": up.get("retries", 1),
        "timeout": {k: _duration(v) for k, v in timeout.items()},
    }
    return (
        "apiVersion: apisix.apache.org/v2\n"
        "kind: ApisixUpstream\n"
        "metadata:\n"
        f"  name: {_k8s_name(service['name'])}\n"
        "  labels:\n"
        "    app: oan-partner-gateway\n"
        "spec:\n"
        "  ingressClassName: {{ .Values.ingressClassName | quote }}\n"
        + _dump(spec, 2)
    )


def route(service: dict) -> str:
    shared = {k: v for k, v in (service.get("plugins") or {}).items() if k != "request-id"}
    out = [
        "apiVersion: apisix.apache.org/v2\n",
        "kind: ApisixRoute\n",
        "metadata:\n",
        f"  name: {_k8s_name(service['name'])}\n",
        "  labels:\n",
        "    app: oan-partner-gateway\n",
        "spec:\n",
        "  ingressClassName: {{ .Values.ingressClassName | quote }}\n",
        "  http:\n",
    ]
    for r in service["routes"]:
        out.append(f"  - name: {r['name']}\n")
        out.append("    match:\n")
        out.append(HOSTS)
        out.append("      paths:\n")
        out.extend(f"      - {uri}\n" for uri in r["uris"])
        out.append("      methods:\n")
        out.extend(f"      - {m}\n" for m in r["methods"])
        out.append("    upstreams:\n")
        out.append(f"    - name: {_k8s_name(service['name'])}\n")
        out.append("    plugins:\n")
        for name, config in {**shared, **(r.get("plugins") or {})}.items():
            out.append(f"    - name: {name}\n")
            out.append("      enable: true\n")
            out.append("      config:\n")
            body = _dump(config, 8)
            if name == "limit-count":
                body += REDIS
            out.append(body)
    return "".join(out)


def main(source: str) -> int:
    adc = yaml.safe_load(Path(source).read_text(encoding="utf-8"))
    services = adc.get("services") or []
    if not services:
        print(f"{source}: no services", file=sys.stderr)
        return 1
    header = HEADER.format(source=Path(source).name)
    upstreams = header + "---\n".join(upstream(s) for s in services)
    routes = header + "---\n".join(route(s) for s in services)
    for placeholder, expression in PLACEHOLDERS.items():
        upstreams = upstreams.replace(placeholder, expression)
        routes = routes.replace(placeholder, expression)
    left = set(re.findall(r"\$\{[A-Z_]+\}", upstreams + routes))
    if left:
        print(f"unmapped ADC placeholders: {sorted(left)}", file=sys.stderr)
        return 1
    (CHART / "templates").mkdir(parents=True, exist_ok=True)
    (CHART / "templates" / "apisix-upstream.yaml").write_text(upstreams, encoding="utf-8", newline="\n")
    (CHART / "templates" / "apisix-route.yaml").write_text(routes, encoding="utf-8", newline="\n")
    count = sum(len(s["routes"]) for s in services)
    print(f"{len(services)} upstreams, {count} routes -> {CHART / 'templates'}")
    return 0


if __name__ == "__main__":
    if len(sys.argv) != 2:
        print(__doc__)
        sys.exit(2)
    sys.exit(main(sys.argv[1]))
