"""Write the `oan-partner-gateway` Helm chart (APISIX Ingress Controller resources) and the
sandbox's scope map from `apis.yaml`, the source of truth of the partner APIs.

    python deploy/apisix-partner-gateway/generate_k8s_chart.py

No arguments, no other input: the same apis.yaml always gives the same files. Written:

    k8s/templates/_shared-plugins.tpl    per API, the plugins every route shares (named
                                         template taking (dict "root" $ "scope" "<scope>"))
    k8s/templates/apisix-upstream.yaml   ApisixUpstream per API (host, timeouts, optional
                                         client certificate for mTLS to the upstream)
    k8s/templates/apisix-pluginconfig.yaml  ApisixPluginConfig per API (its shared plugins)
    k8s/templates/apisix-route.yaml      ApisixRoute per API, one rule per operation
    gateway-scopes.json                  scope map for the sandbox (setting GATEWAY_SCOPES):
                                         "/prefix" -> scope, "METHOD /path" -> scope for an
                                         operation with its own scope

`_helpers.tpl` and `apisix-tls.yaml` are hand-written and left alone.

Access model (every route):

    serverless-pre-function  (rewrite) X-Partner-Token -> Authorization for openid-connect;
                             the caller's Authorization kept aside; client-sent X-OAN-*,
                             X-Userinfo, X-Access-Token dropped (no spoofing)
    openid-connect           signature (realm JWKS), iss, exp; claim_schema: typ Bearer,
                             participant_uid, oan_app, the environment role in
                             oan_environments
    serverless-post-function Authorization restored; aud must hold keycloak.audience (401);
                             X-OAN-Partner-Id / X-OAN-App set; the route's scope must be in
                             the token's `scope` (or, with legacyRouteIds, the route id in
                             oan_routes) else 403; IP whitelist oan_ips (403); app limits
    http-logger              call record to the sandbox (callLog.enabled)
    limit-count              the app's per-minute / per-day limits, 120/min per app and route

An operation with its own `scope` does not use the API's ApisixPluginConfig: its route
carries the plugins inline with that scope (a route's plugins and a plugin config's are
merged by APISIX, so the scope check is not split between the two).
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
SOURCE = HERE / "apis.yaml"
CHART = HERE / "k8s"
SCOPES_FILE = HERE / "gateway-scopes.json"
ROUTE_NAME_MAX = 100
METHODS = {"GET", "POST", "PUT", "PATCH", "DELETE", "HEAD"}
SCOPE_RE = re.compile(r"^[A-Za-z0-9:._-]+$")
HEADER = (
    "# OAN partner APIs (sandbox apps, GATEWAY_PARTNER_AUTH=oauth): APISIX Ingress Controller resources.\n"
    "# Generated by deploy/apisix-partner-gateway/generate_k8s_chart.py from apis.yaml -- do not hand-edit;\n"
    "# change apis.yaml and re-run.\n"
)
# Apps share a gateway and pick routes by host: hosts is required (checked in apisix-tls.yaml).
HOSTS = (
    "      hosts:\n"
    "{{- range .Values.hosts }}\n"
    "      - {{ . | quote }}\n"
    "{{- end }}\n"
)

# ------------------------------------------------------------------ plugin logic
PRE_FUNCTION = """return function(conf, ctx)
  local core = require("apisix.core")
  local token = core.request.header(ctx, "X-Partner-Token")
  local upstream = core.request.header(ctx, "Authorization")
  ctx.oan_x_access_token = core.request.header(ctx, "X-Access-Token")
  for _, name in ipairs({"X-Partner-Token", "X-Access-Token", "X-Userinfo",
                         "X-OAN-Partner-Id", "X-OAN-App", "X-OAN-Upstream-Authorization"}) do
    core.request.set_header(ctx, name, nil)
  end
  if type(token) ~= "string" or token == "" then
    core.response.set_header("WWW-Authenticate", 'Bearer realm="partner"')
    return 401, {message = "Missing app token (X-Partner-Token)"}
  end
  token = token:gsub("^[Bb][Ee][Aa][Rr][Ee][Rr]%s+", "")
  core.request.set_header(ctx, "X-OAN-Upstream-Authorization", upstream)
  core.request.set_header(ctx, "Authorization", "Bearer " .. token)
end"""

# ${AUDIENCE}, ${SCOPE}, ${LEGACY} become Helm expressions (Lua literals) after the dump.
POST_FUNCTION = """return function(conf, ctx)
  local core = require("apisix.core")
  local info = core.request.header(ctx, "X-Userinfo")
  local claims = info and core.json.decode(ngx.decode_base64(info) or "")
  -- jwt-auth with hide_credentials removed it: then the upstream gets no Authorization.
  local upstream = core.request.header(ctx, "X-OAN-Upstream-Authorization")
  core.request.set_header(ctx, "X-Userinfo", nil)
  core.request.set_header(ctx, "X-OAN-Upstream-Authorization", nil)
  core.request.set_header(ctx, "Authorization", upstream)
  core.request.set_header(ctx, "X-Access-Token", ctx.oan_x_access_token)
  if type(claims) ~= "table" or type(claims.participant_uid) ~= "string"
      or type(claims.oan_app) ~= "string" then
    return 401, {message = "Invalid app token"}
  end
  -- Set before the checks below, so a refused call is still logged against its app.
  core.request.set_header(ctx, "X-OAN-Partner-Id", claims.participant_uid)
  core.request.set_header(ctx, "X-OAN-App", claims.oan_app)
  -- The token must be meant for this gateway (aud; empty audience = not checked).
  local audience = ${AUDIENCE}
  if audience ~= "" then
    local aud, meant = claims.aud, false
    if type(aud) == "string" then
      meant = aud == audience
    elseif type(aud) == "table" then
      for _, value in ipairs(aud) do
        if value == audience then
          meant = true
          break
        end
      end
    end
    if not meant then
      return 401, {message = "Token not issued for this gateway"}
    end
  end
  -- The app's API products: the scope this route needs, in the token's scope claim.
  local wanted = ${SCOPE}
  local granted = false
  if type(claims.scope) == "string" then
    for value in string.gmatch(claims.scope, "%S+") do
      if value == wanted then
        granted = true
        break
      end
    end
  end
  -- Migration only (legacyRouteIds): the route ids the token was issued with.
  if not granted and ${LEGACY} and type(claims.oan_routes) == "table" then
    for _, id in ipairs(claims.oan_routes) do
      if id == ctx.route_id then
        granted = true
        break
      end
    end
  end
  if not granted then
    return 403, {message = "This app has no access to this API"}
  end
  -- The app's IP whitelist (oan_ips; empty = any address). A list that cannot be read
  -- refuses the call rather than letting it through.
  local ips = claims.oan_ips
  if type(ips) == "table" and #ips > 0 then
    local matcher = require("resty.ipmatcher").new(ips)
    if not matcher or not matcher:match(ctx.var.remote_addr) then
      return 403, {message = "This app does not accept calls from your IP address"}
    end
  end
  -- The app's own limits (the most generous of its API products; 0 = none), read by
  -- limit-count. A rule whose key is not set does not apply.
  local minute, day = tonumber(claims.oan_limit_minute), tonumber(claims.oan_limit_day)
  if minute and minute > 0 then
    ctx.var.oan_limit_minute = minute
    ctx.var.oan_limit_minute_key = claims.oan_app .. ":minute"
  end
  if day and day > 0 then
    ctx.var.oan_limit_day = day
    ctx.var.oan_limit_day_key = claims.oan_app .. ":day"
  end
end"""

#: Placeholder -> Helm expression; in a shared-plugins template `.root` is the chart root.
EXPRESSIONS = {
    "${ISSUER}": '{{ include "partnerGateway.issuer" .root }}',
    "${DISCOVERY}": '{{ include "partnerGateway.discovery" .root }}',
    "${ENVIRONMENT_ROLE}": '{{ required "environmentRole is required" .root.Values.environmentRole }}',
    "${LOG_URL}": '{{ required "callLog.url is required" .root.Values.callLog.url }}',
    "${AUDIENCE}": '{{ .root.Values.keycloak.audience | default "" | quote }}',
    "${SCOPE}": "{{ .scope | quote }}",
    "${LEGACY}": "{{ if .root.Values.legacyRouteIds }}true{{ else }}false{{ end }}",
}


def plugins(api: dict) -> dict[str, dict]:
    """The plugins every route of ``api`` shares, with placeholders."""
    return {
        "proxy-rewrite": {"regex_uri": [f"^{api['prefix']}/(.*)", "${BASE_PATH}/$1"]},
        "serverless-pre-function": {"phase": "rewrite", "functions": [PRE_FUNCTION]},
        "openid-connect": {
            "client_id": "oan-apisix-gateway",
            "discovery": "${DISCOVERY}",
            "bearer_only": True,
            "use_jwks": True,
            "realm": "partner",
            "set_userinfo_header": True,
            "set_access_token_header": False,
            "iat_slack": 30,
            "accept_unsupported_alg": False,
            "accept_none_alg": False,
            "claim_validator": {"issuer": {"valid_issuers": ["${ISSUER}"]}},
            "claim_schema": {
                "type": "object",
                "required": ["typ", "participant_uid", "oan_app", "oan_environments"],
                "properties": {
                    "typ": {"const": "Bearer"},
                    "participant_uid": {"type": "string", "minLength": 1},
                    "oan_app": {"type": "string", "minLength": 1},
                    "oan_environments": {"type": "array", "contains": {"const": "${ENVIRONMENT_ROLE}"}},
                    "scope": {"type": "string"},
                    # Migration only (legacyRouteIds); optional.
                    "oan_routes": {"type": "array", "items": {"type": "string"}},
                },
            },
        },
        "serverless-post-function": {"phase": "rewrite", "functions": [POST_FUNCTION]},
        "http-logger": {
            "uri": "${LOG_URL}",
            "auth_header": "$env://OAN_SANDBOX_LOG_INGEST_AUTHORIZATION",
            "batch_max_size": 100,
            "inactive_timeout": 5,
            "timeout": 5,
        },
        "limit-count": {
            "rules": [
                {"count": "$oan_limit_minute", "time_window": 60, "key": "$oan_limit_minute_key",
                 "header_prefix": "Minute"},
                {"count": "$oan_limit_day", "time_window": 86400, "key": "$oan_limit_day_key",
                 "header_prefix": "Day"},
                {"count": 120, "time_window": 60, "key": "$http_x_oan_app:$route_id", "header_prefix": "Route"},
            ],
            "rejected_code": 429,
            "rejected_msg": "Rate limit exceeded for this app. Try again later or ask for a higher limit.",
            "show_limit_quota_header": True,
            "allow_degradation": True,
        },
    }


# ------------------------------------------------------------------ YAML helpers
class _Literal(str):
    pass


def _literal(dumper: yaml.Dumper, value: _Literal) -> yaml.ScalarNode:
    return dumper.represent_scalar("tag:yaml.org,2002:str", value, style="|")


yaml.add_representer(_Literal, _literal)


def _blocks(value):
    """Multi-line strings (the serverless Lua) as literal blocks."""
    if isinstance(value, dict):
        return {k: _blocks(v) for k, v in value.items()}
    if isinstance(value, list):
        return [_blocks(v) for v in value]
    if isinstance(value, str) and "\n" in value:
        return _Literal(value)
    return value


def _dump(value, indent: int) -> str:
    text = yaml.dump(_blocks(value), sort_keys=False, default_flow_style=False, width=4096, allow_unicode=True)
    if "{{" in text or "}}" in text:
        raise ValueError("a plugin config holds '{{' or '}}', which Helm would read as a template")
    pad = " " * indent
    return "".join(pad + line if line.strip() else line for line in text.splitlines(True))


def _redis(indent: int) -> str:
    """limit-count counters shared by every APISIX pod when redis.host is set."""
    pad = " " * indent
    return (
        "{{- if .root.Values.redis.host }}\n"
        + f"{pad}policy: redis\n"
        + pad + "redis_host: {{ .root.Values.redis.host | quote }}\n"
        + pad + "redis_port: {{ .root.Values.redis.port }}\n"
        + "{{- end }}\n"
    )


# ------------------------------------------------------------------ apis.yaml
def _segments(path: str) -> list[str]:
    return [s for s in path.strip("/").split("/") if s]


def load(source: Path = SOURCE) -> list[dict]:
    """apis.yaml, checked, with every operation's name, priority and scope filled in."""
    apis = (yaml.safe_load(source.read_text(encoding="utf-8")) or {}).get("apis") or []
    if not apis:
        raise ValueError(f"{source.name}: no apis")
    names, prefixes, route_names = set(), set(), set()
    for api in apis:
        for key in ("name", "values", "prefix", "scope", "operations"):
            if not api.get(key):
                raise ValueError(f"{source.name}: an API without '{key}': {api}")
        if not re.fullmatch(r"[a-z0-9]([a-z0-9-]*[a-z0-9])?", api["name"]) or api["name"] in names:
            raise ValueError(f"{source.name}: bad or repeated API name {api['name']!r}")
        if not re.fullmatch(r"[A-Za-z][A-Za-z0-9]*(\.[A-Za-z][A-Za-z0-9]*)*", api["values"]):
            raise ValueError(f"{api['name']}: values must be a dotted value path, not {api['values']!r}")
        if not re.fullmatch(r"(/[a-z0-9][a-z0-9-]*)+", api["prefix"]) or api["prefix"] in prefixes:
            raise ValueError(f"{api['name']}: bad or repeated prefix {api['prefix']!r}")
        names.add(api["name"])
        prefixes.add(api["prefix"])
        api.setdefault("readTimeout", 30)
        seen = set()
        for op in api["operations"]:
            method, path = str(op.get("method", "")).upper(), str(op.get("path", ""))
            if method not in METHODS or not path.startswith("/"):
                raise ValueError(f"{api['name']}: bad operation {op}")
            if (method, path) in seen:
                raise ValueError(f"{api['name']}: operation {method} {path} listed twice")
            seen.add((method, path))
            op["method"], op["path"] = method, path
            slug = re.sub(r"[^a-z0-9]+", "-", path.lower()).strip("-")
            op.setdefault("name", f"{api['prefix'].strip('/')}-{method.lower()}-{slug}")
            if len(op["name"]) > ROUTE_NAME_MAX or op["name"] in route_names:
                raise ValueError(f"{api['name']}: route name too long or repeated: {op['name']}")
            route_names.add(op["name"])
            if "priority" not in op and ":" in path:
                op["priority"] = sum(not s.startswith(":") for s in _segments(path))
            op["own_scope"] = bool(op.get("scope")) and op["scope"] != api["scope"]
            op.setdefault("scope", api["scope"])
        for scope in {api["scope"], *(op["scope"] for op in api["operations"])}:
            if not SCOPE_RE.fullmatch(scope):
                raise ValueError(f"{api['name']}: scope {scope!r} has characters other than A-Z a-z 0-9 : . _ -")
    return apis


# ------------------------------------------------------------------ chart files
def _template(api: dict) -> str:
    return f"partnerGateway.plugins.{api['name']}"


def _include(api: dict, root: str, scope: str, indent: int) -> str:
    return '{{ include "%s" (dict "root" %s "scope" %s) | indent %d }}\n' % (
        _template(api), root, json.dumps(scope), indent)


def _enabled(api: dict) -> str:
    return "{{- if .Values.%s.enabled }}\n" % api["values"]


def _plugin(name: str, config: dict) -> str:
    body = _dump(config, 4)
    if name == "limit-count":
        body += _redis(4)
    item = f"- name: {name}\n  enable: true\n  config:\n{body}"
    if name == "http-logger":
        # The call log is optional: the sandbox stores the records only when its
        # GATEWAY_LOG_INGEST_ENABLED is on.
        item = "{{- if .root.Values.callLog.enabled }}\n" + item + "{{- end }}\n"
    return item


def shared_plugins(api: dict) -> str:
    """A named template with the API's plugins; call it with (dict "root" $ "scope" "...")."""
    text = "".join(_plugin(name, config) for name, config in plugins(api).items())
    base = '{{ (index (.root.Values.%s | default dict) "basePath") | default "" | trimSuffix "/" }}' % (
        api["values"])
    text = text.replace("${BASE_PATH}", base)
    for placeholder, expression in EXPRESSIONS.items():
        text = text.replace(placeholder, expression)
    left = set(re.findall(r"\$\{[A-Z_]+\}", text))
    if left:
        raise ValueError(f"unmapped placeholders: {sorted(left)}")
    return '{{- define "%s" -}}\n%s{{- end }}\n' % (_template(api), text)


def upstream(api: dict) -> str:
    values = f".Values.{api['values']}"
    return (
        _enabled(api)
        + "{{- $own := %s.upstreamTls | default dict }}\n" % values
        + '{{- $tlsName := $own.secretName | default .Values.upstreamTls.secretName }}\n'
        + '{{- $tlsNamespace := $own.namespace | default .Values.upstreamTls.namespace | default .Release.Namespace }}\n'
        + "apiVersion: apisix.apache.org/v2\n"
        "kind: ApisixUpstream\n"
        "metadata:\n"
        f"  name: {api['name']}\n"
        "  labels:\n"
        "    app: oan-partner-gateway\n"
        "spec:\n"
        "  ingressClassName: {{ .Values.ingressClassName | quote }}\n"
        "  externalNodes:\n"
        "  - type: Domain\n"
        '    name: {{ required "%s.host is required" %s.host }}\n' % (api["values"], values)
        + "    port: 443\n"
        "  scheme: https\n"
        "  passHost: node\n"
        "  retries: 1\n"
        "  timeout:\n"
        "    connect: 10s\n"
        "    send: 30s\n"
        f"    read: {api['readTimeout']}s\n"
        "{{- if $tlsName }}\n"
        "  # mTLS: APISIX presents this client certificate (tls.crt, tls.key) to the upstream,\n"
        "  # whose edge accepts partner calls only with it, so partners cannot skip the gateway.\n"
        "  tlsSecret:\n"
        "    name: {{ $tlsName | quote }}\n"
        "    namespace: {{ $tlsNamespace | quote }}\n"
        "{{- end }}\n"
        "{{- end }}\n"
    )


def plugin_config(api: dict) -> str:
    return (
        "{{- if and .Values.%s.enabled (not .Values.inlineSharedPlugins) }}\n" % api["values"]
        + "apiVersion: apisix.apache.org/v2\n"
        "kind: ApisixPluginConfig\n"
        "metadata:\n"
        f"  name: {api['name']}\n"
        "  labels:\n"
        "    app: oan-partner-gateway\n"
        "spec:\n"
        "  ingressClassName: {{ .Values.ingressClassName | quote }}\n"
        "  plugins:\n"
        + _include(api, ".", api["scope"], 2)
        + "{{- end }}\n"
    )


def route(api: dict) -> str:
    out = [
        _enabled(api),
        "apiVersion: apisix.apache.org/v2\n",
        "kind: ApisixRoute\n",
        "metadata:\n",
        f"  name: {api['name']}\n",
        "  labels:\n",
        "    app: oan-partner-gateway\n",
        "spec:\n",
        "  ingressClassName: {{ .Values.ingressClassName | quote }}\n",
        "  http:\n",
    ]
    for op in api["operations"]:
        out.append(f"  - name: {op['name']}\n")
        if op.get("priority"):
            out.append(f"    priority: {op['priority']}\n")
        out.append("    match:\n")
        out.append(HOSTS)
        out.append("      paths:\n")
        out.append(f"      - {api['prefix']}{op['path']}\n")
        out.append("      methods:\n")
        out.append(f"      - {op['method']}\n")
        out.append("    upstreams:\n")
        out.append(f"    - name: {api['name']}\n")
        if op["own_scope"]:
            # Its own scope: the plugins inline, never the API's plugin config.
            out.append(f"    # Needs scope {op['scope']} (not the API's {api['scope']}).\n")
            out.append("    plugins:\n")
            out.append(_include(api, "$", op["scope"], 4))
        else:
            out.append("{{- if not .Values.inlineSharedPlugins }}\n")
            out.append(f"    plugin_config_name: {api['name']}\n")
            out.append("{{- else }}\n")
            out.append("    plugins:\n")
            out.append(_include(api, "$", api["scope"], 4))
            out.append("{{- end }}\n")
    out.append("{{- end }}\n")
    return "".join(out)


def scope_map(apis: list[dict]) -> dict[str, str]:
    """For the sandbox (GATEWAY_SCOPES): "/prefix" -> scope, then "METHOD /path" -> scope for
    each operation with its own scope (the sandbox matches those first)."""
    mapping = {api["prefix"]: api["scope"] for api in apis}
    for api in apis:
        for op in api["operations"]:
            if op["own_scope"]:
                mapping[f"{op['method']} {api['prefix']}{op['path']}"] = op["scope"]
    return mapping


def main() -> int:
    try:
        apis = load()
        files = {
            "apisix-upstream.yaml": HEADER + "---\n".join(upstream(a) for a in apis),
            "apisix-pluginconfig.yaml": HEADER + "---\n".join(plugin_config(a) for a in apis),
            "apisix-route.yaml": HEADER + "---\n".join(route(a) for a in apis),
            "_shared-plugins.tpl": "{{/*\n" + HEADER + "*/}}\n" + "".join(shared_plugins(a) for a in apis),
        }
    except ValueError as exc:
        print(f"apis.yaml: {exc}", file=sys.stderr)
        return 1
    (CHART / "templates").mkdir(parents=True, exist_ok=True)
    for name, text in files.items():
        (CHART / "templates" / name).write_text(text, encoding="utf-8", newline="\n")
    SCOPES_FILE.write_text(json.dumps(scope_map(apis), indent=2) + "\n", encoding="utf-8", newline="\n")
    count = sum(len(a["operations"]) for a in apis)
    print(f"{len(apis)} APIs, {count} routes -> {CHART / 'templates'}; scopes -> {SCOPES_FILE.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
